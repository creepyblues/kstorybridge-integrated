/**
 * Type guard: Check if response is success
 */
export function isSuccessResponse(
  result: AnalyzePitchResult
): result is AnalyzePitchResponse {
  return result.success === true;
}

/**
 * Type guard: Check if response is error
 */
export function isErrorResponse(
  result: AnalyzePitchResult
): result is AnalyzePitchError {
  return result.success === false;
}

/**
 * Validate asset category
 */
export function isValidAssetCategory(category: string): category is AssetCategory {
  return ['social_media', 'ad_creative', 'pitch_material'].includes(category);
}

/**
 * Validate asset format
 */
export function isValidAssetFormat(format: string): format is AssetFormat {
  const validFormats: AssetFormat[] = [
    '1080x1920',
    '1080x1080',
    '1200x628',
    '1200x675',
    '1280x720',
    '300x250',
    '728x90',
    '1920x1080',
    'custom',
  ];
  return validFormats.includes(format as AssetFormat);
}

// ============================================================================
// COST CALCULATION HELPERS
// ============================================================================

/**
 * GPT-4 Turbo pricing (as of 2025-11-06)
 */
export const GPT4_PRICING = {
  'gpt-4-turbo-preview': {
    input: 0.01 / 1000,    // $0.01 per 1K tokens
    output: 0.03 / 1000,   // $0.03 per 1K tokens
  },
  'gpt-4': {
    input: 0.03 / 1000,    // $0.03 per 1K tokens
    output: 0.06 / 1000,   // $0.06 per 1K tokens
  },
};

/**
 * Calculate GPT-4 cost based on token usage
 */
export function calculateGPT4Cost(
  model: string,
  promptTokens: number,
  completionTokens: number
): number {
  const pricing = GPT4_PRICING[model as keyof typeof GPT4_PRICING] || GPT4_PRICING['gpt-4-turbo-preview'];
  return (promptTokens * pricing.input) + (completionTokens * pricing.output);
}

/**
 * DALL-E 3 pricing (as of 2025-11-06)
 */
export const DALLE3_PRICING = {
  'dall-e-3': 0.040,       // Standard quality: $0.040 per image
  'dall-e-3-hd': 0.080,    // HD quality: $0.080 per image
};

/**
 * Calculate estimated cost for asset generation
 */
export function estimateAssetCost(
  generation_api: GenerationAPI,
  generation_model: GenerationModel
): number {
  if (generation_api === 'dall-e-3') {
    return DALLE3_PRICING[generation_model] || DALLE3_PRICING['dall-e-3'];
  }
  // Future: openai-video pricing
  return 0;
}
