// TypeScript Types for analyze-pitch-for-assets Edge Function
// Feature: Creative Asset Generation System
// Design: Isolated - accepts all data as parameters, NO database queries

// ============================================================================
// REQUEST TYPES (Input from frontend)
// ============================================================================

/**
 * Main request payload for analyzing pitch deck and generating asset ideas
 * ISOLATED DESIGN: All data passed as parameters, no DB lookups required
 */
export interface AnalyzePitchRequest {
  // Title identification (passed from UI, no DB lookup)
  title_id: string;           // External reference (UUID string or any ID)
  title_name: string;          // Displayed in UI, stored in results

  // Pitch deck content (passed from UI)
  pitch_deck_url: string;      // Supabase Storage URL (signed URL with 24h expiry)
  pitch_analysis?: PitchAnalysis; // Optional: Pre-extracted pitch analysis from title_content_analysis

  // Admin context (passed from auth)
  admin_email: string;         // Email of requesting admin (e.g., 'sungho@dadble.com')
}

/**
 * Pitch analysis structure from title_content_analysis.pitch_analysis JSONB field
 * Used to provide context for asset generation without querying database
 */
export interface PitchAnalysis {
  // Character information
  characters?: {
    main_characters?: Array<{
      name?: string;
      role?: string;
      archetype?: string;
      description?: string;
    }>;
    relationships?: string[];
  };

  // Story elements
  story?: {
    logline?: string;
    premise?: string;
    themes?: string[];
    conflicts?: string[];
    narrative_structure?: string;
    setting?: string;
  };

  // Market positioning
  market?: {
    target_audience?: string;
    comparable_titles?: string[];
    unique_selling_points?: string[];
    genre_blend?: string[];
  };

  // Source material metrics
  source_material?: {
    platform?: string;
    views?: number;
    chapters?: number;
    rating?: number;
    completion_status?: string;
  };

  // Cultural elements
  cultural_elements?: {
    korean_cultural_themes?: string[];
    cultural_authenticity_score?: number;
  };

  // Raw text (fallback if structured data incomplete)
  raw_pitch_text?: string;
}

// ============================================================================
// RESPONSE TYPES (Output to frontend)
// ============================================================================

/**
 * Success response with generated asset ideas
 */
export interface AnalyzePitchResponse {
  success: true;
  data: {
    title_id: string;
    title_name: string;
    assets_created: number;         // Count of asset ideas inserted
    asset_ideas: AssetIdea[];       // Array of generated asset ideas
    analysis_metadata: AnalysisMetadata;
  };
}

/**
 * Error response
 */
export interface AnalyzePitchError {
  success: false;
  error: {
    code: string;                   // Error code (e.g., 'PITCH_MISSING', 'OPENAI_ERROR')
    message: string;                // Human-readable error message
    details?: unknown;              // Optional error details
  };
}

/**
 * Union type for response
 */
export type AnalyzePitchResult = AnalyzePitchResponse | AnalyzePitchError;

// ============================================================================
// ASSET IDEA TYPES
// ============================================================================

/**
 * Asset category classification
 */
export type AssetCategory = 'social_media' | 'ad_creative' | 'pitch_material';

/**
 * Asset types by category
 */
export type SocialMediaAssetType =
  | 'instagram_story'
  | 'instagram_post'
  | 'facebook_post'
  | 'twitter_post'
  | 'tiktok_video';

export type AdCreativeAssetType =
  | 'display_ad'
  | 'youtube_thumbnail'
  | 'video_ad'
  | 'banner_ad';

export type PitchMaterialAssetType =
  | 'concept_art'
  | 'key_scene'
  | 'character_card'
  | 'mood_board'
  | 'poster';

export type AssetType = SocialMediaAssetType | AdCreativeAssetType | PitchMaterialAssetType;

/**
 * Asset format (dimensions or video specs)
 */
export type AssetFormat =
  | '1080x1920'    // Instagram Story, TikTok
  | '1080x1080'    // Instagram Square Post
  | '1200x628'     // Facebook Link Post
  | '1200x675'     // Twitter Large Card
  | '1280x720'     // YouTube Thumbnail
  | '300x250'      // Display Ad (Medium Rectangle)
  | '728x90'       // Display Ad (Leaderboard)
  | '1920x1080'    // Video Ad, Concept Art, Poster
  | 'custom';      // Custom dimensions

/**
 * Generation API options
 */
export type GenerationAPI = 'dall-e-3' | 'openai-video';

/**
 * Generation model options
 */
export type GenerationModel = 'dall-e-3' | 'dall-e-3-hd';

/**
 * Asset idea generated by GPT-4
 * Maps directly to title_marketing_assets table structure
 */
export interface AssetIdea {
  // Categorization
  asset_category: AssetCategory;
  asset_type: AssetType;
  asset_format: AssetFormat;

  // Content
  description: string;             // What this asset represents (user-facing)
  prompt_template: string;         // DALL-E 3 prompt generated by GPT-4

  // Generation config
  generation_api: GenerationAPI;
  generation_model: GenerationModel;

  // Metadata (optional, for display/filtering)
  priority?: number;               // 1-5, higher = more important
  estimated_cost?: number;         // Estimated cost in USD
}

// ============================================================================
// ANALYSIS METADATA
// ============================================================================

/**
 * Metadata about the analysis process
 */
export interface AnalysisMetadata {
  // Cost tracking
  gpt4_cost: number;               // Cost of GPT-4 analysis in USD
  total_cost: number;              // Total cost (currently just GPT-4)

  // Timing
  analysis_duration_ms: number;    // Time taken for analysis

  // OpenAI metadata
  model_used: string;              // e.g., 'gpt-4-turbo-preview'
  tokens_used: {
    prompt: number;
    completion: number;
    total: number;
  };

  // Content metadata
  pitch_analysis_used: boolean;    // Whether pitch_analysis was available
  ideas_generated: number;         // Count of ideas generated by GPT-4
}

